#!/usr/bin/env bash
# Regenerates keycodes_gen.go from the kernel's input-event-codes.h.
set -euo pipefail
HDR=${1:-/usr/include/linux/input-event-codes.h}
{
  echo "// Code generated by gen_keycodes.sh from linux/input-event-codes.h. DO NOT EDIT."
  echo
  echo "package main"
  echo
  echo "var rawKeyDefs = [][2]string{"
  grep -E '^#define[[:space:]]+(KEY|BTN)_[A-Z0-9_]+[[:space:]]+[A-Za-z0-9_]+' "$HDR" |
    awk '$2 !~ /_(MAX|CNT)$/ { printf "\t{\"%s\", \"%s\"},\n", $2, $3 }'
  echo "}"
} > keycodes_gen.go
gofmt -w keycodes_gen.go
